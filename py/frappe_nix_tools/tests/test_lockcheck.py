from helpers import run_cli

PYPI = "https://pypi.org/simple"
FILES = "https://files.pythonhosted.org/packages/ab/cd"
SEED = "nix/node-locks/frappe/ui"


def pkg(name, version, source=None, files=None, deps=()):
	source = source or f'registry = "{PYPI}"'
	lines = ["[[package]]", f'name = "{name}"', f'version = "{version}"', f"source = {{ {source} }}"]
	if deps:
		lines.append("dependencies = [" + ", ".join(f'{{ name = "{d}" }}' for d in deps) + "]")
	if files is None:
		files = [f"{FILES}/{name.replace('-', '_')}-{version}-py3-none-any.whl"]
	if files:
		lines.append("wheels = [")
		lines += [f'    {{ url = "{u}", hash = "sha256:{"0" * 64}" }},' for u in files]
		lines.append("]")
	return "\n".join(lines) + "\n"


def uv_lock(*pkgs):
	return ('version = 1\nrequires-python = ">=3.14"\n\n' + "\n".join(pkgs)).encode()


BASE_PKGS = (
	pkg("app", "0.1.0", 'virtual = "."', files=[], deps=("frappe",)),
	pkg("frappe", "16.1.0", 'editable = "apps/frappe"', files=[], deps=("requests", "pypika")),
	pkg("requests", "2.32.3"),
	pkg(
		"pypika",
		"0.51.1",
		f'git = "https://github.com/frappe/pypika?rev={"a" * 40}#{"a" * 40}"',
		files=[],
	),
)
BASE_UV = uv_lock(*BASE_PKGS)


def yarn(*entries):
	out = ["# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.", "# yarn lockfile v1", ""]
	for key, version, resolved in entries:
		out += [f'"{key}":', f'  version "{version}"']
		if resolved is not None:
			out.append(f'  resolved "{resolved}"')
		out += ['  integrity "sha512-x"', ""]
	return ("\n".join(out) + "\n").encode()


def npm(name, version, host="registry.yarnpkg.com"):
	return f"https://{host}/{name}/-/{name.rsplit('/', 1)[-1]}-{version}.tgz#{'b' * 40}"


BASE_YARN = yarn(
	("vue@^3.4.0", "3.4.1", npm("vue", "3.4.1")), ("@vue/shared@3.4.1", "3.4.1", npm("@vue/shared", "3.4.1"))
)
STAMP = b'{\n  "package.json": "' + b"1" * 64 + b'"\n}\n'
BASE = {
	"nix/uv.lock": BASE_UV,
	"nix/node-locks/frappe/ui/yarn.lock": BASE_YARN,
	"nix/node-locks/frappe/ui/source.json": STAMP,
}


def with_(**changes):
	out = dict(BASE)
	for key, value in changes.items():
		path = {"uv": "nix/uv.lock", "yarn": f"{SEED}/yarn.lock", "stamp": f"{SEED}/source.json"}.get(
			key, key
		)
		if value is None:
			out.pop(path, None)
		else:
			out[path] = value
	return out


class TestCheck(unittest.TestCase):
	def decide(self, head, base=BASE, major=None):
		return lockcheck.check(base, head, major)

	def test_unchanged_and_an_honest_bump(self):
		self.assertEqual(self.decide(BASE).decision(), "ok")
		honest = uv_lock(
			pkg("app", "0.1.0", 'virtual = "."', files=[], deps=("frappe",)),
			pkg("frappe", "16.2.0", 'editable = "apps/frappe"', files=[], deps=("requests", "pypika")),
			pkg(
				"requests",
				"2.32.4",
				files=[f"{FILES}/requests-2.32.4-py3-none-any.whl", f"{FILES}/requests-2.32.4.tar.gz"],
			),
			pkg(
				"pypika",
				"0.51.1",
				f'git = "https://github.com/frappe/pypika?rev={"a" * 40}#{"a" * 40}"',
				files=[],
			),
		)
		yarn_bump = yarn(
			("vue@^3.4.0", "3.4.5", npm("vue", "3.4.5", "registry.npmjs.org")),
			("@vue/shared@3.4.1", "3.4.1", npm("@vue/shared", "3.4.1")),
		)
		stamp = b'{\n  "package.json": "' + b"2" * 64 + b'"\n}\n'
		res = self.decide(with_(uv=honest, yarn=yarn_bump, stamp=stamp))
		self.assertEqual(res.decision(), "ok", res.reasons())

	def test_rejects(self):
		cases = {
			"a package from another index": uv_lock(
				pkg("evil", "1.0", 'registry = "https://evil.example/simple"')
			),
			"a file off PyPI": uv_lock(
				pkg("requests", "2.32.4", files=["https://evil.example/requests-2.32.4-py3-none-any.whl"])
			),
			"plain http": uv_lock(
				pkg(
					"requests",
					"2.32.4",
					files=["http://files.pythonhosted.org/requests-2.32.4-py3-none-any.whl"],
				)
			),
			"another package's file": uv_lock(
				pkg("requests", "2.32.4", files=[f"{FILES}/evil-2.32.4-py3-none-any.whl"])
			),
			"another version's file": uv_lock(
				pkg("requests", "2.32.4", files=[f"{FILES}/requests-9.0-py3-none-any.whl"])
			),
			"a url source": uv_lock(
				pkg("requests", "2.32.4", 'url = "https://evil.example/r.whl"', files=[])
			),
			"a new git repository": uv_lock(
				pkg(
					"pypika",
					"0.51.1",
					f'git = "https://github.com/evil/pypika?rev={"c" * 40}#{"c" * 40}"',
					files=[],
				)
			),
			"a new path source": uv_lock(pkg("evil", "1.0", 'path = "nix/node-locks/evil.whl"', files=[])),
			"a file with no url": uv_lock(pkg("requests", "2.32.4").replace('url = "', 'path = "')),
			"same name and version, other files": uv_lock(
				pkg("requests", "2.32.3", files=["https://evil.example/requests-2.32.3-py3-none-any.whl"])
			),
		}
		for why, text in cases.items():
			with self.subTest(why=why):
				res = self.decide(with_(uv=text))
				self.assertEqual(res.decision(), "reject", res.reasons())
		with self.subTest(why="not TOML"):
			self.assertEqual(self.decide(with_(uv=b"[[package]\n")).decision(), "reject")
		with self.subTest(why="deleted"):
			self.assertEqual(self.decide(with_(uv=None)).decision(), "reject")

	def test_yarn_rejects(self):
		cases = {
			"a tarball off the registry": yarn(("vue@^3.4.0", "3.4.5", "https://evil.example/vue-3.4.5.tgz")),
			"plain http": yarn(("vue@^3.4.0", "3.4.5", "http://registry.yarnpkg.com/vue/-/vue-3.4.5.tgz")),
			"another package's tarball": yarn(("vue@^3.4.0", "3.4.5", npm("evil", "3.4.5"))),
			"another version's tarball": yarn(("vue@^3.4.0", "3.4.5", npm("vue", "9.9.9"))),
			"a berry lock": b"__metadata:\n  version: 6\n",
		}
		for why, text in cases.items():
			with self.subTest(why=why):
				res = self.decide(with_(yarn=text))
				self.assertEqual(res.decision(), "reject", res.reasons())

	def test_yarn_read_as_the_build_reads_it(self):
		"""A line the lenient regexes skip but lib/node/yarn-lock.nix (last field wins) and
		fixup-yarn-lock take: the review's proof of concept, and its variants."""
		honest = npm("vue", "3.4.1")
		evil = f'  resolved "https://evil.example.com/vue/-/vue-3.4.1.tgz#{"c" * 40}#x y"'
		poc = BASE_YARN.replace(b'  integrity "sha512-x"\n', b"", 1).replace(
			f'  resolved "{honest}"\n'.encode(), f'  resolved "{honest}"\n{evil}\n'.encode(), 1
		)
		text = poc.decode()
		# what the build would fetch for it: the attacker's tarball
		nix = dict(lockcheck.nix_yarn(text))
		self.assertTrue(nix['"vue@^3.4.0"']["resolved"].startswith("https://evil.example.com/"))
		res = self.decide(with_(yarn=poc))
		self.assertEqual(res.decision(), "reject", res.reasons())
		self.assertTrue(any("not a line yarn writes" in r for r in res.reasons()), res.reasons())
		base_line = f'  resolved "{honest}"\n'.encode()
		cases = {
			"a colon": f'  resolved: "{honest}"\n',
			"a quoted field name": f'  "resolved" "{honest}"\n',
			"a field twice": f'  resolved "{honest}"\n  resolved "{npm("vue", "3.4.1", "registry.npmjs.org")}"\n',
			"a carriage return": f'  resolved "{honest}"\r\n',
			"a line separator": f'  resolved "{honest}"\u2028\n',
			"a tab": f'  resolved\t"{honest}"\n',
			"trailing space": f'  resolved "{honest}" \n',
			"an escape": f'  resolved "{honest}\\u0020"\n',
			"too deep": f'  resolved "{honest}"\n    resolved "https://evil.example.com/x.tgz"\n',
			"two hashes on resolved": '  resolved "sha1-a= sha512-b=="\n',
			"a version twice, bare": f'  resolved "{honest}"\n  version 3.4.1\n',
		}
		for why, line in cases.items():
			with self.subTest(why=why):
				res = self.decide(with_(yarn=BASE_YARN.replace(base_line, line.encode(), 1)))
				self.assertEqual(res.decision(), "reject", res.reasons())
		with self.subTest(why="a spec in two entries"):
			twice = BASE_YARN + yarn(("vue@^3.4.0", "3.4.1", npm("vue", "3.4.1")))[len(yarn()) :]
			self.assertEqual(self.decide(with_(yarn=twice)).decision(), "reject")
		with self.subTest(why="a field before any entry"):
			first = BASE_YARN.replace(b"\n\n", b'\n  resolved "https://evil.example.com/x.tgz"\n\n', 1)
			self.assertEqual(self.decide(with_(yarn=first)).decision(), "reject")

	def test_yarn_as_yarn_writes_it(self):
		"""Everything yarn writes reads strictly, the same as yarn-lock.nix reads it."""
		lock = "\n".join(
			[
				"# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.",
				"# yarn lockfile v1",
				"",
				"",
				'"@vue/shared@3.4.1", "@vue/shared@^3.4.0":',
				'  version "3.4.1"',
				f'  resolved "{npm("@vue/shared", "3.4.1")}"',
				'  integrity "sha1-T0GkEZAhbuNgZ+w4FSb+lTnE8K4= sha512-TN1kCZAgdgweJhWWpgKYrQ=="',
				"",
				'"string-width-cjs@npm:string-width@^4.2.0", string-width@^4.1.0:',
				"  name string-width-cjs",
				'  version "4.2.3"',
				f'  resolved "{npm("string-width", "4.2.3")}"',
				"  integrity sha512-wKyQRQpjJ0sIp62ErSZdGsjMJWsap5oRNihHhu6G7JVO/9jIB6UyevL+tXuOqrng8j/cxKTWyWUwvSTriiZz/g==",
				"  dependencies:",
				'    emoji-regex "^8.0.0"',
				'    "@vue/shared" "^1.0.2 || 2"',
				"  optionalDependencies:",
				'    fsevents "~2.3.2"',
				"",
				'"@flow/ui-core@link:./harness/ui/core":',
				'  version "0.0.0"',
				'  uid ""',
				"",
			]
		)
		parsed = lockcheck.strict_yarn(lock)
		self.assertEqual(parsed.errors, [])
		ours = [
			(k, {f: v for f, v in fs.items() if f in ("version", "resolved", "integrity")})
			for k, fs in parsed.entries
		]
		self.assertEqual(lockcheck.nix_yarn(lock), ours)
		self.assertEqual(parsed.specs["string-width@^4.1.0"]["name"], "string-width-cjs")
		seed = data_path("node-locks/version-16/frappe/ui/yarn.lock").read_text()
		self.assertEqual(lockcheck.strict_yarn(seed).errors, [])
		# a new entry with a name is shown to a person
		cjs = next(b for b in lock.split("\n\n") if b.startswith('"string-width-cjs'))
		res = self.decide(with_(yarn=BASE_YARN + (cjs + "\n\n").encode()))
		self.assertEqual(res.decision(), "needs-review", res.reasons())
		self.assertTrue(any("set a name or uid" in r for r in res.reasons()), res.reasons())

	def test_forced_target_deleted(self):
		forced = b'{\n  "forced": true,\n  "package.json": "' + b"1" * 64 + b'"\n}\n'
		base = with_(stamp=forced)
		res = self.decide({k: v for k, v in base.items() if k != f"{SEED}/source.json"}, base=base)
		self.assertEqual(res.decision(), "reject", res.reasons())
		res = self.decide({k: v for k, v in base.items() if k != f"{SEED}/yarn.lock"}, base=base)
		self.assertEqual(res.decision(), "reject", res.reasons())
		res = self.decide(with_(yarn=None, stamp=None), base=base)
		self.assertEqual(res.decision(), "needs-review", res.reasons())
		# a stamp that does not force anything decides nothing when it goes
		self.assertEqual(self.decide(with_(stamp=None)).decision(), "ok")

	def test_stamp_and_strays(self):
		forced = b'{\n  "forced": true,\n  "package.json": "' + b"1" * 64 + b'"\n}\n'
		cases = {
			"forced turned on": with_(stamp=forced),
			"another key": with_(stamp=b'{"package.json": "' + b"1" * 64 + b'", "lock": "x"}'),
			"not a hash": with_(stamp=b'{"package.json": "x"}'),
			"not JSON": with_(stamp=b"forced"),
			"another file under node-locks": with_(**{f"{SEED}/evil.whl": b"x"}),
			"a new forced target": with_(**{"nix/node-locks/hrms/x/source.json": forced}),
		}
		for why, head in cases.items():
			with self.subTest(why=why):
				res = self.decide(head)
				self.assertEqual(res.decision(), "reject", res.reasons())
		# forced kept as the base has it, with other hashes, is a stamp an honest relock writes
		base = with_(stamp=forced)
		moved = b'{\n  "forced": true,\n  "package.json": "' + b"3" * 64 + b'"\n}\n'
		self.assertEqual(self.decide(with_(stamp=moved), base=base).decision(), "ok")
		self.assertEqual(self.decide(with_(stamp=STAMP), base=base).decision(), "reject")
		# a pruned target is fine
		self.assertEqual(self.decide(with_(yarn=None, stamp=None)).decision(), "ok")

	def test_reviews(self):
		added = uv_lock(*BASE_PKGS, pkg("tzdata", "2025.1"))
		moved_git = BASE_UV.replace(b"a" * 40, b"e" * 40)
		yarn_added = BASE_YARN + yarn(("d3@^7", "7.9.0", npm("d3", "7.9.0")))[len(yarn()) :]
		no_url = BASE_YARN + yarn(("local@file:../x", "1.0.0", None))[len(yarn()) :]
		cases = {
			"a new package": (with_(uv=added), "nix/uv.lock adds tzdata"),
			"a git source at another commit": (with_(uv=moved_git), "another commit of a git source"),
			"a new yarn entry": (with_(yarn=yarn_added), "adds d3"),
			"a yarn entry with no url": (with_(yarn=no_url), "resolve to no URL"),
		}
		for why, (head, reason) in cases.items():
			with self.subTest(why=why):
				res = self.decide(head)
				self.assertEqual(res.decision(), "needs-review", res.reasons())
				self.assertTrue(any(reason in r for r in res.reasons()), res.reasons())

	def test_seed(self):
		"""A new node-lock target that is the seed frappe-nix-tools ships is the seed's."""
		seed_dir = data_path("node-locks/version-16/frappe/ui")
		seed = {
			f"{SEED}/yarn.lock": (seed_dir / "yarn.lock").read_bytes(),
			f"{SEED}/source.json": (seed_dir / "source.json").read_bytes(),
		}
		base = {"nix/uv.lock": BASE_UV}
		self.assertEqual(self.decide({**base, **seed}, base=base, major=16).decision(), "ok")
		res = self.decide({**base, **seed}, base=base, major=None)
		self.assertNotEqual(res.decision(), "ok", "without the major, the seed is a new lock to look at")


def git(root: Path, *args: str) -> str:
	return subprocess.run(
		["git", "-C", str(root), "-c", "user.name=t", "-c", "user.email=t@t", *NO_AUTO_MAINTENANCE, *args],
		check=True,
		capture_output=True,
		text=True,
	).stdout.strip()


class TestVerify(unittest.TestCase):
	def setUp(self):
		tmp = tempfile.TemporaryDirectory()
		self.addCleanup(tmp.cleanup)
		self.root = Path(tmp.name) / "app"
		self.root.mkdir()
		patch = mock.patch.dict(os.environ, {"GIT_CONFIG_GLOBAL": "/dev/null", "HOME": tmp.name})
		patch.start()
		self.addCleanup(patch.stop)
		git(self.root, "init", "-q")
		self.write("pyproject.toml", b"[tool.frappe-nix]\nfrappe-major = 16\n")
		for path, data in BASE.items():
			self.write(path, data)
		git(self.root, "add", "-A")
		git(self.root, "commit", "-qm", "base")
		self.base = git(self.root, "rev-parse", "HEAD")

	def write(self, path, data):
		full = self.root / path
		full.parent.mkdir(parents=True, exist_ok=True)
		full.write_bytes(data)

	def tree(self):
		git(self.root, "add", "-A")
		return git(self.root, "write-tree")

	def cli(self, head):
		return run_cli(
			"ci", "verify-relock", "--base", self.base, "--head", head, "--repo-dir", str(self.root)
		)

	def test_tree_and_commit(self):
		self.write("nix/uv.lock", BASE_UV + b"\n" + pkg("tzdata", "2025.1").encode())
		code, out, err = self.cli(self.tree())
		self.assertEqual((code, out.splitlines()[0]), (0, "needs-review"), err)
		git(self.root, "commit", "-qm", "relock")
		code, out, _ = self.cli(git(self.root, "rev-parse", "HEAD"))
		self.assertEqual((code, out.splitlines()[0]), (0, "needs-review"))
		self.assertEqual(self.cli(self.base)[:2], (0, "ok\n"))

	def test_reject_exits_1(self):
		self.write("nix/uv.lock", uv_lock(pkg("evil", "1.0", 'registry = "https://evil.example/simple"')))
		code, out, _ = self.cli(self.tree())
		self.assertEqual(code, 1)
		self.assertIn("::error::refusing the relock", out)

	def test_symlink_and_mode(self):
		os.symlink("/etc/passwd", self.root / SEED / "x")
		code, out, _ = self.cli(self.tree())
		self.assertEqual(code, 1, out)
		self.assertIn("not a regular file", out)

	def test_bad_ids(self):
		for base, head in (("HEAD", "a" * 40), (self.base, "HEAD"), (self.base[:12], self.base)):
			with self.subTest(base=base, head=head), self.assertRaises(ConfigError):
				lockcheck.verify(self.root, base, head)

	def test_frappe_major_from_the_base(self):
		self.assertEqual(lockcheck.frappe_major(self.root, self.base), 16)
		self.write("pyproject.toml", b"[project]\n")
		git(self.root, "commit", "-qam", "no major")
		self.assertIsNone(lockcheck.frappe_major(self.root, git(self.root, "rev-parse", "HEAD")))


if __name__ == "__main__":
	unittest.main()
