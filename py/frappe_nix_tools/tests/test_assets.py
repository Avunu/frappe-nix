class TestVueTypeScript5(ViteApp):
	"""A Vite app with Vue single-file components, beside the typescript floor (the native
	TypeScript 7, which has no JS API): the typescript5 alias, scripts/vue-tsc.cjs for an SPA's
	check, and scripts/vue-sfc-typescript.mjs for the Vite config to import, so Vue's SFC
	compiler can read the types defineProps<T>() imports. That they run is checked by hand
	(docs/app-standards/assets.md); their format and lint are the standards-vue-typescript
	nix check."""

	TSC = "scripts/vue-tsc.cjs"
	SFC = "scripts/vue-sfc-typescript.mjs"

	def vue_app(self, *, spa: bool = True, vue: str = "demo_app/public/js/spa/App.vue") -> None:
		self.write(vue, "<template><p /></template>\n")
		self.write("demo_app/public/js/spa/main.ts", "export {};\n")
		self.write("tsconfig.json", '{ "compilerOptions": {} }\n')
		if spa:
			self.table(
				'typescript.spa = [{ root = ".", include = ["demo_app/public/js/spa/**"],'
				' tsconfig = "tsconfig.json", check = "node scripts/vue-tsc.cjs --noEmit -p tsconfig.json" }]\n'
			)
		self.vite_app()

	def dev(self) -> dict:
		return json.loads(self.read("package.json"))["devDependencies"]

	def test_a_vue_vite_app_gets_both_and_the_alias(self):
		self.vue_app()
		self.synced()
		for path in (self.TSC, self.SFC):
			text = self.read(path)
			self.assertTrue(text.startswith("// frappe-nix:managed — generated by frappe-nix"), text[:120])
			self.assertNotIn("{#", text)
			self.assertNotIn("\t", text)
			for line in text.splitlines()[1:]:
				if not line.startswith("// See https://"):
					self.assertLessEqual(len(line), 80, line)
		self.assertIn('require("vue-tsc").run(require.resolve("typescript5/lib/tsc"));', self.read(self.TSC))
		self.assertIn(
			'require("vue/compiler-sfc").registerTS(() => require("typescript5"));', self.read(self.SFC)
		)
		self.assertEqual(self.dev()["typescript5"], "npm:typescript@^5.9.3")
		self.assertEqual(self.dev()["typescript"], "^7.0.2")
		pkg = json.loads(self.read("package.json"))
		self.assertIn("node scripts/vue-tsc.cjs --noEmit -p tsconfig.json", pkg["scripts"]["typecheck"])
		# The Vite config's side-effect import of the helper is not an oxlint error.
		rc = json.loads(self.read(".oxlintrc.json"))
		self.assertIn(
			{"files": ["vite.config.ts"], "rules": {"import/no-unassigned-import": "off"}}, rc["overrides"]
		)

	def test_an_apps_own_shim_becomes_the_managed_one(self):
		"""messaging and erpnext_taskview wrote scripts/vue-tsc.cjs themselves: sync takes it
		over in place, so their SPA checks keep their command."""
		self.write(self.TSC, 'require("vue-tsc").run(require.resolve("typescript5/lib/tsc"));\n')
		self.vue_app()
		self.synced()
		self.assertTrue(self.read(self.TSC).startswith("// frappe-nix:managed"))

	def test_the_apps_alias_range_stands_when_it_meets_the_floor(self):
		self.vue_app()
		self.synced()
		pkg = json.loads(self.read("package.json"))
		for have, want in (
			("npm:typescript@^5.9.4", "npm:typescript@^5.9.4"),
			("npm:typescript@6.0.2", "npm:typescript@6.0.2"),
			("npm:typescript@^5.4.0", "npm:typescript@^5.9.3"),
			("^5.9.3", "npm:typescript@^5.9.3"),
		):
			pkg["devDependencies"]["typescript5"] = have
			self.write("package.json", json.dumps(pkg, indent="\t") + "\n")
			self.commit()
			self.assertEqual(self.fn("sync", "--write")[0], 0)
			self.assertEqual(self.dev()["typescript5"], want, have)

	def test_without_vite_only_the_vue_tsc_shim(self):
		self.write("demo_app/public/js/spa/App.vue", "<template><p /></template>\n")
		self.write("demo_app/public/js/spa/main.ts", "export {};\n")
		self.write("tsconfig.json", '{ "compilerOptions": {} }\n')
		self.table(
			'typescript.spa = [{ root = ".", include = ["demo_app/public/js/spa/**"],'
			' tsconfig = "tsconfig.json", check = "node scripts/vue-tsc.cjs --noEmit -p tsconfig.json" }]\n'
		)
		self.write("package.json", json.dumps({"name": "demo-app"}))
		self.commit()
		self.synced()
		self.assertTrue((self.root / self.TSC).is_file())
		self.assertFalse((self.root / self.SFC).exists())
		self.assertIn("typescript5", self.dev())

	def test_no_vue_or_only_a_nested_frontends_no_files(self):
		self.write("frontend/package.json", '{"name": "frontend"}\n')
		self.write("frontend/src/App.vue", "<template><p /></template>\n")
		self.write("docs-site/.vitepress/theme/Layout.vue", "<template><p /></template>\n")
		self.write("demo_app/public/js/main.ts", "export {};\n")
		self.vite_app()
		self.synced()
		self.assertFalse((self.root / self.TSC).exists())
		self.assertFalse((self.root / self.SFC).exists())
		self.assertNotIn("typescript5", self.dev())
		rc = json.loads(self.read(".oxlintrc.json"))
		self.assertNotIn(["vite.config.ts"], [o["files"] for o in rc["overrides"]])

	def test_module_off_removes_them_and_the_alias(self):
		self.vue_app()
		self.synced()
		self.table("typescript.enable = false\n")
		self.commit()
		code, _, err = self.fn("sync", "--write")
		self.assertEqual(code, 0, err)
		self.assertFalse((self.root / self.TSC).exists())
		self.assertFalse((self.root / self.SFC).exists())
		self.assertNotIn("typescript5", json.loads(self.read("package.json")).get("devDependencies", {}))

	def test_an_edited_copy_is_drift(self):
		self.vue_app()
		self.synced()
		self.write(self.SFC, self.read(self.SFC) + "// mine\n")
		code, out = self.check()
		self.assertEqual(code, 1, out)
		self.assertIn(f"{self.SFC} (whole)", out)
