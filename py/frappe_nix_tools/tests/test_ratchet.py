class TestR5(RatchetCase):
	def test_nosemgrep_without_rule_fails(self) -> None:
		self.write("demo_app/a.py", "frappe.db.commit()  # nosemgrep\n")
		git(self.root, "add", "-A")
		self.assert_fails("R5")

	def test_nosemgrep_without_reason_fails(self) -> None:
		self.write("demo_app/a.py", "x = 1\nfrappe.db.commit()  # nosemgrep: frappe-manual-commit\n")
		git(self.root, "add", "-A")
		self.assert_fails("R5")

	def test_nosemgrep_with_reason_passes(self) -> None:
		self.write(
			"demo_app/a.py",
			"# the scheduler job owns its transaction\nfrappe.db.commit()  # nosemgrep: frappe-manual-commit\n"
			"frappe.db.commit()  # nosemgrep: frappe-manual-commit -- same job, second batch\n",
		)
		git(self.root, "add", "-A")
		self.assert_passes()


