"""``frappe-nix ratchet`` (spec §5.9 R1-R7, S24, §7 N4 "ratchet")."""

import json
import unittest

from scaffold_helpers import AppCase, git


class RatchetCase(AppCase):
	"""``self.base`` is the commit the table is committed in; edits after it are head."""

	base_extra = ""

	def setUp(self) -> None:
		super().setUp()
		if self.base_extra:
			self.write("pyproject.toml", self.read("pyproject.toml") + self.base_extra)
		self.base_setup()
		self.commit()
		self.base = git(self.root, "rev-parse", "HEAD").strip()

	def base_setup(self) -> None:
		pass

	def ratchet(self) -> tuple[int, str, str]:
		return self.fn("ratchet", "--base", self.base)

	def append(self, text: str) -> None:
		self.write("pyproject.toml", self.read("pyproject.toml") + text)

	def assert_fails(self, rule: str) -> str:
		code, out, err = self.ratchet()
		self.assertEqual(code, 1, out + err)
		self.assertIn(rule, out)
		return out

	def assert_passes(self) -> None:
		code, out, err = self.ratchet()
		self.assertEqual(code, 0, out + err)


class TestInactive(AppCase):
	def test_base_without_table_is_inactive(self) -> None:
		table = self.read("pyproject.toml")
		self.write("pyproject.toml", table.split("[tool.frappe-nix]")[0])
		self.commit()
		base = git(self.root, "rev-parse", "HEAD").strip()
		self.write("pyproject.toml", table.replace("fail_under = 50", "fail_under = 10"))
		code, _out, err = self.fn("ratchet", "--base", base)
		self.assertEqual(code, 0)
		self.assertIn("no [tool.frappe-nix]", err)


