def baseline(*findings: tuple[str, str, int]) -> str:
	return json.dumps(
		{
			"schema": 1,
			"findings": [{"rule": r, "path": p, "line_sha1": "a" * 40, "count": c} for r, p, c in findings],
		}
	)


