"""``frappe-nix-node-modules <bench-root> <app>...``: keep each app's mutable
dev ``node_modules`` in step with the app's manifests. Was bash in
lib/node-modules.nix; tests/node-modules.sh is its
acceptance suite.

The dev shell installs node_modules per app with a plain ``yarn install``,
outside Nix, because a nested frontend's postinstall needs the network the
sandbox does not have. That install has to be skipped once it is done — a
``yarn install`` per app on every shell entry costs minutes — and the obvious
sentinel, a bare ``touch node_modules/.frappe-nix-installed``, answers the wrong
question: it records *that* an install happened, never *what* it installed. So
the first ``bench update`` that pulls an app whose package.json gained a
dependency left the sentinel in place, the shell kept skipping, and the build
died on a package nothing ever fetched (``Cannot find package '@framework/ui'
imported from apps/helpdesk/desk/vite.config.js``), which no amount of
re-entering the shell repaired.

The sentinel holds a fingerprint of every manifest the install reads — the
app's own package.json and yarn.lock and each nested frontend's — so a pull
that changes any of them is what triggers the reinstall. The fingerprint is the
one the bash computed, byte for byte (``find | sort -z | xargs sha256sum |
sha256sum``), so a sentinel written by either is honoured by the other.

The fingerprint alone still answers only for the manifests, not for the
installs: the app's own install (whose node_modules holds the sentinel) runs a
postinstall that installs each nested frontend's node_modules too, and those can
go while the sentinel stays. App mode's refresh of the pinned apps used to carry
only apps/<app>/node_modules across, so erpnext came out "installed" with no
banking/node_modules, and ``bench build`` died on ``vite: command not found``.
So the sentinel's second line lists the nested node_modules the install left
(``nested ["banking/node_modules"]``), and one of them missing is a reinstall
too. A sentinel without that line, written before it existed, is believed only
while no nested frontend that declares dependencies lacks node_modules. And
``--carry OLD NEW`` is what the refresh now moves them across with, nested ones
included.

yarn is taken from PATH on purpose: the dev shell pins its own nodejs and yarn
(``frappe-nix.nodejs``), and a yarn baked in here would shadow the pinned one.

An app whose lockfile is pnpm's (``pnpm-lock.yaml``) installs with pnpm, also
from PATH (the shell carries the major its package.json names), and with
``--frozen-lockfile``: yarn 1 in a folder whose yarn.lock is gone exits 0
having resolved every range afresh, so an app that moved to pnpm would get
unpinned packages and no error (frappe/suite#980). The lockfile picks the
manager, as python-devops-nix's lib.node does for the Nix build; one folder
with both locks is refused rather than guessed at. pnpm keeps the shell's
version even when devEngines names another (``pnpm_config_pm_on_fail``), so
the shell and the Nix build install with the same pnpm.

Runs on every shell entry, so it imports nothing it does not need until an
install is due.
"""

import hashlib
import os
import sys
from collections.abc import Iterator, Sequence

NAME = "frappe-nix-node-modules"
SENTINEL = ".frappe-nix-installed"

#: What every walk of an app skips. node_modules holds thousands of
#: package.json files, all outputs of the very install this decides whether to
#: run; nothing under .git is an input to yarn. The rest are what following an
#: app-mode symlink makes necessary: the app-mode bench is materialised inside
#: the repository, and descending into it would count a full copy of frappe's
#: manifests as the app's.
PRUNE = frozenset({"node_modules", ".git", ".frappe-nix", ".devenv", ".direnv"})
MANIFESTS = frozenset({"package.json", "yarn.lock", "pnpm-lock.yaml", "pnpm-workspace.yaml"})
LOCKFILES = frozenset({"yarn.lock", "package-lock.json", "pnpm-lock.yaml"})


class Refused(Exception):
	"""An app this cannot install: the message says what to do."""


def install_command(app: str) -> list[str]:
	"""The frozen install for apps/APP: pnpm's when its lockfile is pnpm's,
	yarn's otherwise (every app before pnpm, and a lockless one, as before)."""
	pnpm = os.path.isfile(f"apps/{app}/pnpm-lock.yaml")
	if pnpm and os.path.isfile(f"apps/{app}/yarn.lock"):
		raise Refused(
			f"apps/{app} has pnpm-lock.yaml and yarn.lock; one folder installs with one "
			"package manager — delete the lockfile it does not use"
		)
	if pnpm:
		return ["pnpm", "install", "--frozen-lockfile"]
	return ["yarn", "install", "--frozen-lockfile"]


def _say(*lines: str, err: bool = False) -> None:
	stream = sys.stderr if err else sys.stdout
	if err:
		sys.stdout.flush()
	for line in lines:
		print(line, file=stream, flush=True)


def walk(top: str, names: frozenset[str]) -> Iterator[str]:
	"""The paths under TOP named one of NAMES, as ``find -H TOP <prune> -name …``
	prints them: TOP followed when it is a symlink (app mode's apps/<app> is
	one), nothing below it followed, PRUNE never descended into."""
	for parent, dirs, files in os.walk(top):
		dirs[:] = [d for d in dirs if d not in PRUNE]
		for name in files:
			if name in names:
				yield os.path.join(parent, name)


def nested_installs(top: str) -> list[str]:
	"""The node_modules directories below TOP's own, relative to TOP and sorted:
	what a postinstall's ``cd <frontend> && yarn install`` leaves. Never looked for
	inside a node_modules, nor under PRUNE; a symlink (<app>/public/node_modules,
	the link to the app's own) is not an install."""
	found: list[str] = []
	for parent, dirs, _files in os.walk(top):
		path = os.path.join(parent, "node_modules")
		if "node_modules" in dirs and parent != top and not os.path.islink(path):
			found.append(os.path.relpath(path, top))
		dirs[:] = [d for d in dirs if d not in PRUNE]
	return sorted(found)


def _declares_dependencies(path: str) -> bool:
	import json

	try:
		with open(path) as f:
			manifest = json.load(f)
	except (OSError, ValueError):
		return False
	return isinstance(manifest, dict) and any(
		manifest.get(key) for key in ("dependencies", "devDependencies")
	)


def _uninstalled_frontends(top: str) -> list[str]:
	"""Nested frontends under TOP (a package.json below TOP's own) that declare
	dependencies and have no node_modules: the guess for a sentinel that lists no
	nested installs."""
	missing: list[str] = []
	for parent, dirs, files in os.walk(top):
		dirs[:] = [d for d in dirs if d not in PRUNE]
		if parent == top or "package.json" not in files:
			continue
		if not os.path.isdir(os.path.join(parent, "node_modules")) and _declares_dependencies(
			os.path.join(parent, "package.json")
		):
			missing.append(os.path.relpath(parent, top))
	return sorted(missing)


def _sha256_file(path: str) -> str:
	h = hashlib.sha256()
	with open(path, "rb") as f:
		for block in iter(lambda: f.read(1 << 16), b""):
			h.update(block)
	return h.hexdigest()


def _sum_line(digest: str, path: str) -> bytes:
	"""One line of ``sha256sum PATH``, with coreutils' escaping of a name that
	holds a backslash or a line break."""
	name = os.fsencode(path)
	if any(c in name for c in (b"\\", b"\n", b"\r")):
		name = name.replace(b"\\", b"\\\\").replace(b"\n", b"\\n").replace(b"\r", b"\\r")
		return b"\\" + digest.encode() + b"  " + name + b"\n"
	return digest.encode() + b"  " + name + b"\n"


def fingerprint(app: str) -> str:
	"""Every manifest ``yarn install`` reads under apps/APP, hashed together with
	its path, so a nested frontend appearing or disappearing counts as a change
	too. Relative to the bench root, which is the working directory."""
	total = hashlib.sha256()
	for path in sorted(walk(f"apps/{app}", MANIFESTS), key=os.fsencode):
		try:
			total.update(_sum_line(_sha256_file(path), path))
		except OSError:
			continue  # a dangling link: nothing yarn could read either
	return total.hexdigest()


def _sentinel(app: str) -> str:
	import json

	return f"{fingerprint(app)}\nnested {json.dumps(nested_installs(f'apps/{app}'))}\n"


def _read(path: str) -> str:
	try:
		with open(path) as f:
			return f.read().rstrip("\n")
	except (OSError, UnicodeDecodeError):
		return ""


def current(app: str) -> bool:
	"""Whether apps/APP's sentinel still describes it: the same manifests, and
	every nested node_modules the install left still there."""
	import json

	lines = _read(f"apps/{app}/node_modules/{SENTINEL}").split("\n")
	if lines[0] != fingerprint(app):
		return False
	if len(lines) > 1 and lines[1].startswith("nested "):
		try:
			nested = json.loads(lines[1].removeprefix("nested "))
		except ValueError:
			return False
		return isinstance(nested, list) and all(
			isinstance(rel, str) and os.path.isdir(os.path.join("apps", app, rel)) for rel in nested
		)
	return not _uninstalled_frontends(f"apps/{app}")


def carry(old: str, new: str) -> list[str]:
	"""Move OLD's node_modules, its own and every nested frontend's, to the same
	place under NEW, where NEW has that directory: what app mode's refresh of
	the pinned apps keeps instead of reinstalling. Replaces what NEW has there.
	The paths moved, relative to OLD."""
	import shutil

	moved: list[str] = []
	for parent, dirs, _files in os.walk(old):
		if "node_modules" in dirs:
			rel = os.path.relpath(os.path.join(parent, "node_modules"), old)
			dest = os.path.join(new, rel)
			if os.path.isdir(os.path.dirname(dest)):
				if os.path.lexists(dest):
					if os.path.isdir(dest) and not os.path.islink(dest):
						shutil.rmtree(dest)
					else:
						os.remove(dest)
				os.rename(os.path.join(parent, "node_modules"), dest)
				moved.append(rel)
		dirs[:] = [d for d in dirs if d not in PRUNE]
	return sorted(moved)


def _snapshot(app: str, snap: str) -> None:
	"""Copy APP's lockfiles, nested frontends included, under SNAP.

	An app's lockfiles belong to the app's repository, not to this bench. The
	install is frozen and never writes one, but the postinstall of most apps
	runs a non-frozen ``yarn install`` in each nested frontend, which rewrites a
	tracked lock or writes one where upstream ships none: dirty, and the app's
	next ``git checkout`` refuses over it. yarn 1 has no switch for the nested
	installs, so the install is bracketed: copy the locks first, put back
	whatever it changed. A lock already edited is in the copy, so it comes back
	edited; only yarn's own rewrite is undone. Hash-free and git-free, so it
	behaves the same for an app that is not a repository."""
	import shutil

	os.makedirs(os.path.join(snap, "apps", app), exist_ok=True)
	for path in walk(f"apps/{app}", LOCKFILES):
		dest = os.path.join(snap, path)
		os.makedirs(os.path.dirname(dest), exist_ok=True)
		shutil.copy2(path, dest)


def _restore(app: str, snap: str) -> None:
	import filecmp
	import shutil

	# Written or rewritten by the install.
	for path in sorted(walk(f"apps/{app}", LOCKFILES)):
		saved = os.path.join(snap, path)
		if not os.path.lexists(saved):
			os.remove(path)
			_say(f"  · {path}: created by the install, removed")
		elif not filecmp.cmp(path, saved, shallow=False):
			shutil.copy2(saved, path)
			_say(f"  · {path}: rewritten by the install, put back")
	# Deleted by it.
	saved_root = os.path.join(snap, "apps", app)
	for parent, _dirs, files in sorted(os.walk(saved_root)):
		for name in sorted(files):
			path = os.path.relpath(os.path.join(parent, name), snap)
			if not os.path.lexists(path):
				os.makedirs(os.path.dirname(path), exist_ok=True)
				shutil.copy2(os.path.join(parent, name), path)
				_say(f"  · {path}: deleted by the install, put back")


def _install(app: str, argv: Sequence[str]) -> tuple[bool, str]:
	"""ARGV (install_command's) in apps/APP, its output captured: whether it
	worked, and the last 20 lines of what it said."""
	import signal
	import subprocess
	import tempfile

	with tempfile.TemporaryFile() as log:
		try:
			proc = subprocess.Popen(
				list(argv),
				cwd=f"apps/{app}",
				# The logical path, as `cd apps/<app>` would leave it: in app mode
				# apps/<app> is a symlink to the repository.
				env={
					"pnpm_config_pm_on_fail": "ignore",
					**os.environ,
					"PWD": os.path.join(os.environ.get("PWD") or os.getcwd(), "apps", app),
				},
				stdin=subprocess.DEVNULL,
				stdout=log,
				stderr=subprocess.STDOUT,
			)
		except OSError as e:
			return False, f"{argv[0]}: {e.strerror}"
		try:
			status = proc.wait()
		except KeyboardInterrupt:
			if proc.poll() is None:
				proc.send_signal(signal.SIGINT)
			proc.wait()
			raise
		log.seek(0)
		tail = log.read().decode(errors="replace").splitlines()[-20:]
	return status == 0, "\n".join(tail)


def _which(tool: str) -> bool:
	for directory in os.environ.get("PATH", "").split(os.pathsep):
		candidate = os.path.join(directory or ".", tool)
		if os.path.isfile(candidate) and os.access(candidate, os.X_OK):
			return True
	return False


def refresh(apps: Sequence[str]) -> int:
	"""Install what is out of date among APPS, from the bench root (the working
	directory): 0, or 1 when an install failed, was refused or an app is not
	checked out, 2 when an install is due and its manager is not on PATH."""
	failed: list[str] = []
	absent: list[str] = []

	for app in apps:
		nm = f"apps/{app}/node_modules"

		# The app list is what Nix saw, and with `self.submodules = true` Nix
		# fetches every submodule itself, checked out or not. In an app that is
		# not checked out, `yarn install` finds no package.json, succeeds having
		# done nothing, and leaves node_modules/ behind: a directory git will then
		# not clone the app into, and a sentinel that fingerprints nothing.
		if not os.path.isfile(f"apps/{app}/package.json"):
			absent.append(app)
			continue

		# An earlier frappe-nix symlinked the Nix-built node_modules here. Those
		# are built with --ignore-scripts and are read-only, so nested frontends
		# have no deps and nothing can be edited: replace it with a real install.
		try:
			target = os.readlink(nm)
		except OSError:
			target = ""
		if target.startswith("/nix/store/"):
			_say(f"Replacing Nix store node_modules symlink for {app}...")
			os.remove(nm)

		if current(app):
			continue

		try:
			argv = install_command(app)
		except Refused as e:
			_say(f"  ⚠  {e}", err=True)
			failed.append(app)
			continue
		if not _which(argv[0]):
			_say(f"{NAME}: {argv[0]} is not on PATH — cannot install {app}", err=True)
			return 2

		_say(f"Installing node_modules for {app} (incl. nested frontends)...")
		import shutil
		import tempfile

		snap = tempfile.mkdtemp()
		try:
			_snapshot(app, snap)
			try:
				installed, tail = _install(app, argv)
			finally:
				# Whether or not it worked: a failed install can have rewritten a
				# lock too, and so can one cut short.
				_restore(app, snap)
		finally:
			shutil.rmtree(snap, ignore_errors=True)
		if installed:
			# Re-read rather than reuse the one above: a postinstall
			# (patch-package) can rewrite a manifest, and recording the
			# pre-install value would make every later run reinstall from
			# scratch. After the restore, so the locks it put back are what is
			# recorded, not what yarn wrote.
			os.makedirs(nm, exist_ok=True)
			with open(f"{nm}/{SENTINEL}", "w") as f:
				f.write(_sentinel(app))
			_say(f"  ✓ {app}")
		else:
			_say(f"  ⚠  {argv[0]} install failed for {app} — node_modules left as it was:", err=True)
			if tail:
				_say(tail, err=True)
			failed.append(app)

	if absent:
		_say(
			"node_modules not installed for apps with no package.json on disk (not checked out?):",
			*(f"  apps/{app}" for app in absent),
			err=True,
		)
	if failed:
		_say(
			"",
			"node_modules is out of date for:",
			*(f"  {app}" for app in failed),
			"Fix the error above — anything built until then is built against",
			"the previous install.",
			err=True,
		)
		return 1
	# Not an install failure, but not an install either: `bench build` must not
	# go on as if these apps had their node_modules.
	return 1 if absent else 0


def main(argv: Sequence[str] | None = None) -> int:
	args = list(sys.argv[1:] if argv is None else argv)
	if args[:1] == ["--carry"]:
		if len(args) != 3:
			_say(f"usage: {NAME} --carry <old-app-dir> <new-app-dir>", err=True)
			return 2
		try:
			carry(args[1], args[2])
		except OSError as e:
			_say(f"{NAME}: --carry: {e}", err=True)
			return 1
		return 0
	if len(args) < 2:
		_say(f"usage: {NAME} <bench-root> <app>...", err=True)
		return 2
	# The bench root as `cd` would name it, symlinks kept: yarn runs below it.
	logical = os.path.normpath(os.path.join(os.environ.get("PWD") or os.getcwd(), args[0]))
	try:
		os.chdir(args[0])
	except OSError as e:
		_say(f"{NAME}: {args[0]}: {e.strerror}", err=True)
		return 1
	os.environ["PWD"] = logical
	try:
		return refresh(args[1:])
	except KeyboardInterrupt:
		return 130


if __name__ == "__main__":
	sys.exit(main())
